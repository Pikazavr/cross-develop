    private void DeleteButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_DeleteButtonActionPerformed
        int selectedRow = jTable1.getSelectedRow();
        if (selectedRow != -1){
            list.remove(selectedRow);
            javax.swing.table.DefaultTableModel model =
                    (javax.swing.table.DefaultTableModel) jTable1.getModel();
            model.removeRow(selectedRow);
        }else {
            javax.swing.JOptionPane.showMessageDialog(this, "Choose, delete row!");
        }
    }//GEN-LAST:event_DeleteButtonActionPerformed

    private void addButtonActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_addButtonActionPerformed
         try {
        double a = Double.parseDouble(NPtextfield.getText());
        double b = Double.parseDouble(VPtextfield.getText());
        double h = Double.parseDouble(StepTextfield.getText());

        // создаём объект и проверяем
        RecIntegral rec = new RecIntegral(a, b, h, 0);
        list.add(rec);

        javax.swing.table.DefaultTableModel model = 
                (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.addRow(new Object[]{a, b, h, 0});

    } catch (InvalidRecIntegralException e) {
        javax.swing.JOptionPane.showMessageDialog(this, e.getMessage(),
                "Некорректные данные", javax.swing.JOptionPane.WARNING_MESSAGE);
    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Введите корректные числа",
                "Ошибка ввода", javax.swing.JOptionPane.WARNING_MESSAGE);
    } catch (Exception e) {
        javax.swing.JOptionPane.showMessageDialog(this, "Произошла ошибка: " + e.getMessage(),
                "Ошибка", javax.swing.JOptionPane.ERROR_MESSAGE);
    }   
    }//GEN-LAST:event_addButtonActionPerformed

