    private void BackCollectionActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BackCollectionActionPerformed
        javax.swing.table.DefaultTableModel model= 
                    (javax.swing.table.DefaultTableModel) jTable1.getModel();
        model.setRowCount(0);
        for (RecIntegral r : list){
            
            model.addRow(new Object[]{
            r.a,
            r.b,
            r.h,
            r.result,
        });
        }
    }//GEN-LAST:event_BackCollectionActionPerformed

